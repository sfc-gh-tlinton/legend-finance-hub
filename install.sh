#!/usr/bin/env bash
# Legend Finance Hub installer
# Creates the database, simulated finance data, semantic view, Cortex Agent, what-if functions,
# month-end close workflow (rules, email, daily task) and configures the local React app.
#
# Usage:  ./install.sh                    (interactive, prompts with defaults)
#         CONNECTION=myconn DB=LEGENDBIO WAREHOUSE=COMPUTE_WH ROLE=ACCOUNTADMIN \
#         NOTIFY_EMAIL=me@company.com ADD_TO_COWORK=y START_DAILY_TASK=n ./install.sh -y
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
BUILD="$HERE/.build"
YES="${1:-}"

ask() { # ask VAR "Question" default
  local var="$1" q="$2" def="$3" cur="${!1:-}"
  if [[ -n "$cur" ]]; then return; fi
  if [[ "$YES" == "-y" ]]; then printf -v "$var" '%s' "$def"; return; fi
  read -r -p "$q [$def]: " ans
  printf -v "$var" '%s' "${ans:-$def}"
}

command -v snow >/dev/null || { echo "Snowflake CLI (snow) not found. Install: https://docs.snowflake.com/en/developer-guide/snowflake-cli/installation/installation"; exit 1; }

DEFAULT_CONN="$(snow connection list --format json 2>/dev/null | python3 -c 'import sys,json; d=json.load(sys.stdin); print(next((c["connection_name"] for c in d if c.get("is_default")), d[0]["connection_name"] if d else ""))' 2>/dev/null || true)"
ask CONNECTION   "Snowflake CLI connection name" "${DEFAULT_CONN:-default}"
ask DB           "Database to create" "LEGENDBIO"
ask WAREHOUSE    "Warehouse to use" "COMPUTE_WH"
ask ROLE         "Role to install with (needs CREATE DATABASE, CREATE INTEGRATION, EXECUTE TASK)" "ACCOUNTADMIN"
ask NOTIFY_EMAIL "Verified email of a user in this account for close notifications" "you@example.com"
ask ADD_TO_COWORK "Add the agent to Snowflake CoWork / Intelligence? (y/n)" "y"
ask START_DAILY_TASK "Start the daily 7am ET close-check task (emails on new issues)? (y/n)" "n"

for v in DB WAREHOUSE ROLE; do
  [[ "${!v}" =~ ^[A-Za-z_][A-Za-z0-9_$]*$ ]] || { echo "$v must be a simple identifier, got '${!v}'"; exit 1; }
done
[[ "$NOTIFY_EMAIL" =~ ^[^@\ \']+@[^@\ \']+$ ]] || { echo "NOTIFY_EMAIL looks invalid: $NOTIFY_EMAIL"; exit 1; }
DB="$(echo "$DB" | tr '[:lower:]' '[:upper:]')"; WAREHOUSE="$(echo "$WAREHOUSE" | tr '[:lower:]' '[:upper:]')"; ROLE="$(echo "$ROLE" | tr '[:lower:]' '[:upper:]')"

echo; echo "Installing into $DB with role $ROLE, warehouse $WAREHOUSE (connection $CONNECTION)"
snow connection test -c "$CONNECTION" >/dev/null && echo "✓ connection OK"

render() { # render <src> <dst>
  sed -e "s/__DB__/$DB/g" -e "s/__WAREHOUSE__/$WAREHOUSE/g" -e "s/__ROLE__/$ROLE/g" -e "s/__NOTIFY_EMAIL__/$NOTIFY_EMAIL/g" "$1" > "$2"
}
sql_file() { snow sql -c "$CONNECTION" --enable-templating NONE -f "$1" > "$BUILD/$(basename "$1").log" 2>&1 || { echo "✗ $(basename "$1") failed — see $BUILD/$(basename "$1").log"; tail -15 "$BUILD/$(basename "$1").log"; exit 1; }; }
sql_q() { snow sql -c "$CONNECTION" --enable-templating NONE -q "$1"; }

rm -rf "$BUILD"; mkdir -p "$BUILD"
for f in "$HERE"/snowflake/*.sql; do
  render "$f" "$BUILD/$(basename "$f")"
done

steps=(
  "00_setup.sql:Database and schemas"
  "01_seed_data.sql:Simulated GL, AR, AP, budget, close, profit split, FinOps data"
  "02_views.sql:Income statement, balance sheet, aging, recon and forecast views"
  "03_scenarios.sql:What-if scenario functions"
  "04_close_workflow.sql:Close rules, issues, approvals, email integration, daily task"
  "05_semantic_view.sql:Semantic view LEGEND_FINANCE_SV"
  "06_agent.sql:Cortex Agent LEGEND_FINANCE_AGENT"
)
for s in "${steps[@]}"; do
  f="${s%%:*}"; label="${s#*:}"
  printf "… %-70s" "$label"; sql_file "$BUILD/$f"; echo "✓"
done

if [[ "$ADD_TO_COWORK" =~ ^[Yy] ]]; then
  SI="$(snow sql -c "$CONNECTION" --format json -q "show snowflake intelligences" 2>/dev/null | python3 -c 'import sys,json; d=json.load(sys.stdin); print(d[0]["name"] if d else "")' 2>/dev/null || true)"
  if [[ -n "$SI" ]]; then
    sql_q "alter snowflake intelligence $SI add agent $DB.FINANCE.LEGEND_FINANCE_AGENT" >/dev/null 2>&1 || true
    echo "✓ Agent added to Snowflake Intelligence object $SI"
  else
    echo "✓ No Snowflake Intelligence object in this account — agents appear in CoWork automatically"
  fi
fi

if [[ "$START_DAILY_TASK" =~ ^[Yy] ]]; then
  sql_q "alter task $DB.FINANCE.LEGEND_DAILY_CLOSE_CHECKS resume" >/dev/null && echo "✓ Daily close-check task started (7:00 AM ET)"
else
  echo "• Daily close-check task created but suspended. Start it with: ALTER TASK $DB.FINANCE.LEGEND_DAILY_CLOSE_CHECKS RESUME;"
fi

# app configuration
render "$HERE/app/app.yml.template" "$HERE/app/app.yml"
cat > "$HERE/app/.env.local" <<EOF
# Generated by install.sh
SNOWFLAKE_CONNECTION_NAME=$CONNECTION
SNOWFLAKE_WAREHOUSE=$WAREHOUSE
SNOWFLAKE_ROLE=$ROLE
LEGEND_DB=$DB
EOF
echo "✓ App configured (app/.env.local, app/app.yml)"

if command -v npm >/dev/null; then
  printf "… %-70s" "Installing app dependencies (npm ci)"
  (cd "$HERE/app" && npm ci --no-audit --no-fund > "$BUILD/npm.log" 2>&1) && echo "✓" || { echo "✗ see $BUILD/npm.log"; exit 1; }
else
  echo "• npm not found — install Node.js 20+ and run: cd app && npm ci"
fi

cat <<EOF

Done. Start the app:
  cd app && npm run dev -- -p 3010
  open http://localhost:3010

Chat with the agent in CoWork: https://ai.snowflake.com  (agent: Legend Finance Assistant)
EOF
